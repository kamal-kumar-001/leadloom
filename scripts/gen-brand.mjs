// Single source of truth: apps/web/app/tokens.css. Run `node scripts/gen-brand.mjs`
// (also runs before the contracts build). Writes the email palette and syncs the ui copy.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'apps/web/app/tokens.css');
const css = readFileSync(src, 'utf8');
const light = css.slice(css.indexOf('\n[data-theme="light"] {'));
const dark = css.slice(css.indexOf('[data-theme="dark"] {'), css.indexOf('\n[data-theme="light"] {'));
const palette = (block) => {
  const hex = (n) => { const m = new RegExp(`--${n}:\\s*(#[0-9a-fA-F]{6})`).exec(block); if (!m) throw new Error('token missing: ' + n); return m[1].toLowerCase(); };
  const glow = /--accent-loom-glow:\s*rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/.exec(block);
  if (!glow) throw new Error('token missing: accent-loom-glow');
  const surface = hex('bg-surface');
  const mix = (i) => { const a = Number(glow[4]); const s = parseInt(surface.slice(1 + i * 2, 3 + i * 2), 16); return Math.round(Number(glow[1 + i]) * a + s * (1 - a)); };
  const accentSoft = '#' + [0, 1, 2].map((i) => mix(i).toString(16).padStart(2, '0')).join('');
  return { canvas: hex('bg-canvas'), surface, elevated: hex('bg-elevated'), borderSubtle: hex('border-subtle'), textPrimary: hex('text-primary'), textSecondary: hex('text-secondary'), textMuted: hex('text-muted'), accent: hex('accent-loom'), onAccent: hex('on-accent'), accentSoft };
};
const lightBrand = palette(light);
const darkBrand = palette(dark);
const fmt = (o) => `{
${Object.entries(o).map(([k, v]) => `  ${k}: '${v}',`).join('\n')}
} as const`;
const out = `// GENERATED by scripts/gen-brand.mjs from apps/web/app/tokens.css. Do not edit.
export const BRAND_NAME = 'LeadLoom';

// Light-theme palette (kept for any light-surface mail).
export const EMAIL_BRAND = ${fmt(lightBrand)};

// Dark-theme palette: the app's default theme, used for transactional OTP mail
// so the email matches the product Kamal and users actually see.
export const EMAIL_BRAND_DARK = ${fmt(darkBrand)};
`;
writeFileSync(resolve(root, 'packages/contracts/src/brand.contract.ts'), out);
writeFileSync(resolve(root, 'packages/ui/src/tokens.css'), css);
console.log('brand tokens generated, light accent', lightBrand.accent, 'dark accent', darkBrand.accent);
