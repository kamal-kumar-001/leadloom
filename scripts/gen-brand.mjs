// Single source of truth: apps/web/app/tokens.css. Run `node scripts/gen-brand.mjs`
// (also runs before the contracts build). Writes the email palette and syncs the ui copy.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'apps/web/app/tokens.css');
const css = readFileSync(src, 'utf8');
const light = css.slice(css.indexOf('\n[data-theme="light"] {'));
const hex = (n) => { const m = new RegExp(`--${n}:\\s*(#[0-9a-fA-F]{6})`).exec(light); if (!m) throw new Error('token missing: ' + n); return m[1].toLowerCase(); };
const glow = /--accent-loom-glow:\s*rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/.exec(light);
if (!glow) throw new Error('token missing: accent-loom-glow');
const surface = hex('bg-surface');
const mix = (i) => { const a = Number(glow[4]); const s = parseInt(surface.slice(1 + i * 2, 3 + i * 2), 16); return Math.round(Number(glow[1 + i]) * a + s * (1 - a)); };
const accentSoft = '#' + [0, 1, 2].map((i) => mix(i).toString(16).padStart(2, '0')).join('');
const out = `// GENERATED by scripts/gen-brand.mjs from apps/web/app/tokens.css [data-theme="light"]. Do not edit.
export const BRAND_NAME = 'LeadLoom';

export const EMAIL_BRAND = {
  canvas: '${hex('bg-canvas')}',
  surface: '${surface}',
  elevated: '${hex('bg-elevated')}',
  borderSubtle: '${hex('border-subtle')}',
  textPrimary: '${hex('text-primary')}',
  textSecondary: '${hex('text-secondary')}',
  textMuted: '${hex('text-muted')}',
  accent: '${hex('accent-loom')}',
  onAccent: '${hex('on-accent')}',
  accentSoft: '${accentSoft}',
} as const;
`;
writeFileSync(resolve(root, 'packages/contracts/src/brand.contract.ts'), out);
writeFileSync(resolve(root, 'packages/ui/src/tokens.css'), css);
console.log('brand tokens generated, accent', hex('accent-loom'), 'soft', accentSoft);
