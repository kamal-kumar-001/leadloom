#!/usr/bin/env node
import {createHash} from 'node:crypto';
import {readdirSync,readFileSync,lstatSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
export const generated=['apps/engine/src/release-identity.generated.ts','apps/web/lib/release-identity.generated.ts'];
const directories=['apps','packages','workers','skills','scripts','docker'];
const rootFiles=['package.json','package-lock.json','tsconfig.base.json','turbo.json','pnpm-workspace.yaml','docker-compose.yml','.dockerignore','update.sh'];
const skipped=new Set(['node_modules','.next','dist','.git','.turbo','coverage','test-results','playwright-report','blob-report']);
const extensions=new Set(['.ts','.tsx','.js','.jsx','.mjs','.cjs','.json','.css','.scss','.svg','.html','.md','.yml','.yaml','.sh','.prisma','.sql','.toml','.txt','.png','.jpg','.jpeg','.webp','.ico','.woff','.woff2','.ttf']);
export function sourceIdentity(root){
 const files=[];
 const inspect=relative=>{
  const full=path.join(root,relative),stat=lstatSync(full);
  if(stat.isSymbolicLink())throw Error('Build identity refuses symbolic links in the included source set');
  if(stat.isDirectory()){for(const name of readdirSync(full).sort())if(!skipped.has(name)&&!name.startsWith('.env'))inspect(path.posix.join(relative,name));return;}
  if(!stat.isFile()||generated.includes(relative)||relative.endsWith('.tsbuildinfo')||relative.includes('/.env')||relative.endsWith('.log'))return;
  if(!extensions.has(path.extname(relative))&&!relative.endsWith('Dockerfile'))return;
  files.push(relative);
 };
 for(const directory of directories)inspect(directory);
 for(const name of rootFiles){const stat=lstatSync(path.join(root,name));if(!stat.isFile()||stat.isSymbolicLink())throw Error('Expected regular build configuration file');files.push(name);}
 const hash=createHash('sha256').update('leadloom-source-build-v1\0');
 for(const file of files.sort()){const data=readFileSync(path.join(root,file));hash.update(file+'\0'+data.byteLength+'\0');hash.update(data);hash.update('\0');}
 return{buildId:hash.digest('hex'),fileCount:files.length,scheme:'leadloom-source-build-v1'};
}
export function prepare(root){
 const result=sourceIdentity(root),body='// Generated by scripts/ops/build-identity.mjs. Never trust a runtime environment override.\nexport const RELEASE_BUILD_ID = '+JSON.stringify(result.buildId)+';\n';
 for(const relative of generated)writeFileSync(path.join(root,relative),body);
 return result;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const root=fileURLToPath(new URL('../../',import.meta.url));
 try{const args=process.argv.slice(2);if(args.length>1||args.length===1&&args[0]!=='--prepare')throw Error('Use --prepare to embed identity, or no options to inspect it');console.log(JSON.stringify(args[0]==='--prepare'?prepare(root):sourceIdentity(root)));}catch(error){console.error(error instanceof Error?error.message:'Build identity failed');process.exitCode=1;}
}
